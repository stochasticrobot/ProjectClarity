"""Expose output pressure and whole-list requirements through the production CLI.

Unlike an always-successful responder, this transport refuses oversized review
work with a provider-shaped max_tokens response. Its independently chosen output
costs approximate verbose factual and inclusion judgments; they do not simulate a
real tokenizer or prove live-model accuracy. All packing, validation, persistence,
reporting and stopping code is production code, with no node substitutions.
"""
import copy
import json
import unittest
from unittest.mock import patch

from projectclarity.claim_review.qualification import LEGACY_POLICY, POLICY, requirement_catalog
from projectclarity.coverage.stopping import completion_status
from projectclarity.research_schemas import ResearchSession
from projectclarity.research_results import result_progress
from tests.claim_review.mapping_fixtures import fixture_eligibility, fixture_mappings
from tests.research.adversarial_source_scenarios import SourceScenario

WHOLE_LIST = 'Reconcile every district and vacancy exactly once across the complete roster.'
DATED_ROSTER = 'Use an authoritative roster dated on or near the requested research date.'


class ReviewCapacityTests(unittest.TestCase):
    """Require usable individual reviews without claiming unfinished lists are complete."""

    def run_population(self, cap=8192, crowded=False):
        """Run a dated, sixteen-entry collection against an output-limited responder.

        Args:
            self: Test owner registering isolated files and transport cleanup.
            cap: Actual CLI response-token limit sent to the provider adapter.
            crowded: Put eight result records in one claim to test an oversized
                indivisible candidate, rather than ordinary multi-claim packing.
        Returns:
            Typed session, saved run path, review requests and coverage payloads.
            Individual evidence is positive; the independently authored whole-list
            reconciliation judgment stays partial. No live services are contacted.
        """
        scenario = SourceScenario(self, count=16, arrivals=0, concurrency=1)
        case = scenario.case
        case.schema['as_of'] = '2026-10-30'
        case.schema['sections'][0]['evidence_requirements'] = [DATED_ROSTER, WHOLE_LIST]
        original = case.provider
        reviews, coverages = [], []

        def provider(request):
            """Apply output pressure and answer-level gaps at the actual SDK boundary.

            Args:
                request: Serialized HTTP request generated by the production adapter.
            Returns:
                Provider-shaped complete or truncated response. Cost is calculated
                independently of the production estimator; negative scope behavior
                follows the supplied requirement kinds, not expected test outcomes.
            """
            wire = json.loads(request.content)
            title = wire['output_config']['format']['schema']['title']
            payload = json.loads(wire['messages'][0]['content'])
            if title == 'ExtractionBatch' and crowded:
                response = original(request)
                body = json.loads(response.content)
                batch = json.loads(body['content'][0]['text'])
                rows = [c for c in batch['claims'] if c.get('result_records')]
                if len(rows) >= 8:
                    combined = copy.deepcopy(rows[0])
                    combined['result_records'] = [c['result_records'][0] for c in rows[:8]]
                    combined['statement'] = 'Eight source entries supplied together.'
                    batch['claims'] = [combined, *rows[8:]]
                return case.cli.response(text=json.dumps(batch))
            if title == 'ClaimReviewBatch':
                assessments = []
                for candidate in payload['candidates']:
                    decisions = fixture_eligibility(candidate, payload)
                    requirements = {r['requirement_id']: r for rs in payload['report_requirements'].values() for r in rs}
                    for decision in decisions:
                        if requirements[decision['requirement_id']]['kind'] == 'evidence':
                            decision.update(verdict='unknown', evidence_quotes=[],
                                rationale='One entry cannot establish whole-list reconciliation or a dated roster.')
                    assessments.append(dict(candidate_id=candidate['candidate_id'], verdict='supported', in_scope=True,
                        rationale='The assigned source supports these particular field values.',
                        evidence_quotes=[candidate['proposal']['evidence'][0]['quote']],
                        report_mappings=fixture_mappings(candidate, payload), eligibility_assessments=decisions))
                # Independent stress oracle: verbose factual/mapping output plus
                # 450 tokens of quotation/attribution/reasoning for each inclusion.
                cost = sum(400 + 450 * len(a['eligibility_assessments']) for a in assessments)
                reviews.append(dict(payload=payload, cap=wire['max_tokens'], cost=cost))
                if cost > wire['max_tokens']:
                    return case.cli.response(text='{"assessments":[', stop_reason='max_tokens')
                return case.cli.response(text=json.dumps(dict(assessments=assessments)))
            if title == 'CoverageAssessment':
                coverages.append(payload)
                return case.cli.response(text=json.dumps(dict(assessments=[dict(
                    criterion_id=c['criterion_id'], judgment='partial', items=[],
                    result_goal_id=c['result_goal_id'], target_count=c['target_count'],
                    benchmark_candidate_ids=[], evidence_candidate_ids=[c['candidate_id'] for c in payload['candidates']],
                    gaps=[WHOLE_LIST], rationale='The individual entries are supported but roster reconciliation is unfinished.')
                    for c in payload['criteria']], scope_estimates=[], next_searches=[])))
            return original(request)

        case.flow.provider = provider
        with patch('projectclarity.retrieval.retrieval_limits.time.sleep'):
            _, directory, saved, _ = case.flow.run_workflow('--design-answer', '--assess-coverage',
                '--stop-when-satisfied', '--max-requests', '60', '--model-concurrency', '1',
                '--max-output-tokens', str(cap))
        return ResearchSession.model_validate(saved), directory, reviews, coverages

    def test_output_limited_reviews_drain_at_three_real_response_caps(self):
        """Keep all sixteen entries reviewable at 2048, 4096 and 8192 output tokens.

        Args:
            self: Test owner comparing independently enforced capacity and saved results.
        Returns:
            None; no truncation, candidate loss or duplicate submissions are allowed.
            The smaller configured cap must actually produce smaller review groups.
        """
        largest = []
        for cap in (2048, 4096, 8192):
            session, _, calls, _ = self.run_population(cap)
            self.assertTrue(calls)
            self.assertTrue(all(c['cap'] == cap and c['cost'] <= cap for c in calls))
            ids = [c['candidate_id'] for call in calls for c in call['payload']['candidates']]
            self.assertEqual(len(ids), len(set(ids)))
            self.assertEqual(set(ids), {c['candidate_id'] for c in session.extraction['candidates']})
            self.assertTrue(all(not r['error_code'] for r in session.claim_reviews.values()))
            result = result_progress(session.model_dump(mode='json'))['goals'][0]['results']
            self.assertEqual((result['field_supported'], result['supported']), (16, 16))
            largest.append(max(sum(bool(candidate['proposal']['result_records'])
                                   for candidate in call['payload']['candidates']) for call in calls))
        self.assertLess(largest[0], largest[1])
        self.assertLess(largest[1], largest[2])

    def test_individuals_qualify_while_section_evidence_still_blocks_completion(self):
        """Keep section requirements in whole-answer assessment without deleting them.

        Args:
            self: Test owner inspecting real request payloads, report and stop result.
        Returns:
            None; individual counts can advance, but unfinished reconciliation cannot
            turn into a complete answer. No wording-specific classifier is used.
        """
        session, directory, calls, coverage = self.run_population()
        result = result_progress(session.model_dump(mode='json'))['goals'][0]['results']
        self.assertEqual(result['supported'], 16)
        for call in calls:
            self.assertEqual({r['kind'] for rs in call['payload']['report_requirements'].values() for r in rs},
                             {'scope', 'currentness'})
        self.assertTrue(coverage)
        for payload in coverage:
            for criterion in payload['criteria']:
                self.assertIn(WHOLE_LIST, criterion['evidence_required'])
                self.assertIn(DATED_ROSTER, criterion['evidence_required'])
        self.assertFalse(completion_status(session, directory.parent)['ready'])
        self.assertIn(WHOLE_LIST, str(session.coverage))

    def test_oversized_single_candidate_is_not_exempt_from_output_bounds(self):
        """Reject a too-large intact claim before spending on a predictably oversized reply.

        Args:
            self: Test owner checking saved failure and remaining independent work.
        Returns:
            None; the oversized claim is retained with an explicit error and no call,
            while smaller neighbors still receive usable reviews. No partial JSON is salvaged.
        """
        session, _, calls, _ = self.run_population(crowded=True)
        oversized = {cid for cid, r in session.claim_reviews.items() if r['error_code'] == 'review_output_budget_exceeded'}
        self.assertTrue(oversized)
        sent = {c['candidate_id'] for call in calls for c in call['payload']['candidates']}
        self.assertFalse(oversized & sent)
        self.assertTrue(sent)
        self.assertTrue(all(c['cost'] <= c['cap'] for c in calls))
        self.assertFalse(any(r['error_code'] == 'incomplete_model_output' for r in session.claim_reviews.values()))

    def test_saved_v1_contract_does_not_silently_acquire_v2_approvals(self):
        """Bind the new entry-check policy without reinterpreting historical receipts.

        Args:
            self: Test owner comparing requirements for the same saved specification.
        Returns:
            None; v1 retains section requirements and IDs distinct from v2. Arbitrary
            unfamiliar section wording stays at answer level, not guessed by keywords.
        """
        from tests.research.test_contract_completion import explicit_specification
        schema = explicit_specification(2)
        schema['as_of'] = '2026-10-30'
        schema['sections'][0]['evidence_requirements'] = ['Compare the complete archive using protocol X.']
        old, new = requirement_catalog(schema, LEGACY_POLICY)['G1'], requirement_catalog(schema, POLICY)['G1']
        self.assertIn('evidence', {r['kind'] for r in old})
        self.assertEqual({r['kind'] for r in new}, {'scope', 'currentness'})
        self.assertFalse({r['requirement_id'] for r in old} & {r['requirement_id'] for r in new})
