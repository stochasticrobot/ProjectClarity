"""Check the optional preliminary source study before the main research loop.

The real command-line workflow uses synthetic model, search and page responses.
Tests inspect study routing, source selection, quotation references, page reuse,
shared limits and interrupted-request recovery. They also distinguish a skipped
study, an unknown scope and an explicitly allowed model-only estimate. The study
must not claim complete research or turn search snippets into source evidence.
"""
import json
import unittest
from unittest.mock import patch

import httpx2

from projectclarity.discovery.search_provider import SearchProviderError
from tests.planning import test_planning_cli_integration as planning
from tests.research import test_workflow_control_cli as workflow
from tests.retrieval.retrieval_test_fixtures import FakeHTTP, public_dns

QUOTE = 'The synthetic roster lists 7 researchers.'


class EarlyCoverageStudyTests(unittest.TestCase):
    """Keep a bounded preliminary estimate distinct from normal research findings."""

    def setUp(self):
        """Prepare deterministic provider/search/source transports with real graph execution.

        Args:
            self: Case owning an isolated saved-run directory and synthetic controls.
        Returns:
            None. Install transport fixtures; unexpected real networking stays forbidden.
        """
        self.cli = planning.PlanningCLIIntegrationTests()
        self.cli.setUp()
        self.addCleanup(self.cli.doCleanups)
        self.cli.plan['clarifications'] = []
        self.schemas, self.payloads, self.searches = [], [], []
        self.needed, self.search_blocked, self.crash, self.invalid_quote = True, False, False, False
        self.seed_ids = []
        self.selection_ids = None
        self.selection_crash = False
        self.selection_failure = False
        self.result_overrides = {}
        self.estimate_override = None
        self.provider_failure = False
        self.change_source = False
        self.readiness = {'answer_type': 'enumeration', 'evidence_scope': 'mixed',
            'numeric_estimate_applicable': True, 'unresolved_questions': [],
            'coverage_checks': [{'goal_ids': ['G1', 'G2'], 'description': 'Check the roster and its scope.',
                'kind': 'evidence_sufficiency', 'evidence_required': ['Source text establishing the roster boundary.'],
                'assessment_method': 'Compare the evidenced roster with the stated scope.'}]}
        self.study_outcome = 'established'
        self.no_estimates = False
        self.plan_queries = [{'query': q, 'goal_ids': ['G1'], 'reason': 'Find a defensible scope boundary.'}
            for q in ('broad coverage overview', 'independent coverage benchmark')]
        self.routes = {('example.org', '/robots.txt'): (200, {'Content-Type': 'text/plain'}, b'User-agent: *\nAllow: /\n'),
            ('example.org', '/research'): (200, {'Content-Type': 'text/plain'}, QUOTE.encode())}
        for query in range(2):
            for item in range(5):
                self.routes[('example.org', f'/probe-{query}-{item}')] = (200, {'Content-Type': 'text/plain'}, QUOTE.encode())
        self.http = FakeHTTP(self.routes)
        for target, effect in (
            ('projectclarity.retrieval.public_url_fetcher.urllib3.HTTPSConnectionPool', self.http.pool),
            ('projectclarity.nodes.web_search.node.search_web', self.search)):
            substitute = patch(target, side_effect=effect)
            substitute.start()
            self.addCleanup(substitute.stop)

    def search(self, query, max_results, monitor=None):
        """Return actual-result-shaped leads or a typed unavailable-search failure.

        Args:
            self: Case retaining every attempted logical query.
            query: Actual query generated by the planner or coverage-study model.
            max_results: Production result cap respected by the fixture.
            monitor: Unmodified production progress/cancellation observer.
        Returns:
            Five ranked synthetic leads or an explicit per-query override for a
            study query, otherwise no results. Raise SearchProviderError when the
            test selects blocked search; all responses obey the requested cap.
        """
        self.searches.append(query)
        if self.search_blocked:
            raise SearchProviderError('search_provider_blocked')
        queries = [p['query'] for p in self.plan_queries]
        if query not in queries:
            return []
        index = queries.index(query)
        if index in self.result_overrides:
            return self.result_overrides[index][:max_results]
        return [{'url': f'https://example.org/probe-{index}-{i}', 'title': 'Synthetic roster',
            'snippet': 'SNIPPET_ONLY_NOT_SOURCE_EVIDENCE'} for i in range(min(5, max_results))]

    def provider(self, request):
        """Respond to the real SDK schema and record what each graph stage actually sees.

        Args:
            self: Case controlling study decisions, failure and invalid evidence.
            request: Actual serialized SDK request intercepted at the HTTP boundary.
        Returns:
            Provider-shaped response or an abrupt interruption during selection or assessment.
            Unknown tasks fail explicitly instead of silently using a fabricated reply.
        """
        body = json.loads(request.content)
        title = body['output_config']['format']['schema']['title']
        self.schemas.append(title)
        if title == 'ResearchPlan':
            self.assertFalse(self.http.requests)
            self.assertFalse(self.searches)
            return self.cli.response()
        payload = json.loads(body['messages'][0]['content'])
        self.payloads.append((title, payload))
        if title == 'CoverageStudyPlan':
            self.assertEqual(payload['phase'], 'plan')
            self.assertFalse(self.searches)
            self.assertFalse(self.http.requests)
            answer = {'needed': self.needed, 'reason': 'Synthetic decision.',
                'plan': ['Check the bounded source sample for a roster or scope boundary.'],
                'queries': self.plan_queries, 'source_ids': self.seed_ids, 'readiness': self.readiness}
        elif title == 'CoverageStudySelection':
            self.assertEqual(payload['phase'], 'selection')
            self.assertFalse(self.http.requests)
            if self.selection_crash:
                self.selection_crash = False
                raise SystemExit(77)
            if self.selection_failure:
                return httpx2.Response(401, json={'type': 'error', 'error': {'type': 'authentication_error', 'message': 'synthetic rejection'}})
            ids = self.selection_ids
            if ids is None:
                ids = list(self.seed_ids)
                offered = {c['candidate_id'] for c in payload['candidates']}
                ids.extend(i for i in ['R1', 'R6', 'R2', 'R7'] if i in offered)
                ids = ids[:4]
            answer = {'selections': [{'candidate_id': i, 'reason': 'Synthetic coverage-value ranking.'} for i in ids]}
        elif title == 'CoverageStudyAssessment':
            if self.crash:
                self.crash = False
                raise SystemExit(77)
            if self.provider_failure:
                return httpx2.Response(503, json={'type': 'error', 'error': {'type': 'api_error', 'message': 'synthetic outage'}})
            pages = payload['pages']
            self.assertLessEqual(len(pages), 4)
            self.assertNotIn('SNIPPET_ONLY_NOT_SOURCE_EVIDENCE', json.dumps(pages))
            if self.change_source:
                directory, _ = self.cli.saved_session()
                (directory / f"documents/{pages[0]['source_id']}/text.txt").write_text('Changed source after model input.')
            estimate = {'goal_ids': ['G1'], 'unit': 'researchers in the synthetic roster',
                'range': {'lower': 7, 'upper': 7} if pages else {'lower': 5, 'upper': 15},
                'basis': 'evidence_informed' if pages else 'provisional_prior',
                'method': 'Small roster probe' if pages else 'Uncalibrated model estimate',
                'rationale': 'Synthetic fixture, not actual population evidence.', 'assumptions': [],
                'limitations': ['This cannot establish the full population.'],
                'evidence': [{'source_id': pages[0]['source_id'],
                    'quote': 'SNIPPET_ONLY_NOT_SOURCE_EVIDENCE' if self.invalid_quote else QUOTE}] if pages else []}
            if self.estimate_override:
                estimate.update(self.estimate_override)
            answer = {'summary': 'Preliminary scope only.', 'coverage_boundary': 'One synthetic roster, not all researchers.',
                'coverage_outcome': self.study_outcome, 'readiness': self.readiness,
                'estimates': [] if self.no_estimates else [estimate], 'limitations': ['Not a completion certificate.']}
        elif title == 'ExtractionBatch':
            answer = {'entities': [], 'claims': []}
        elif title == 'SearchSourceSelection':
            answer = {'selections': []}
        elif title == 'CoverageAssessment':
            answer = {'assessments': [{'criterion_id': c['criterion_id'], 'judgment': 'unknown',
                'items': [], 'target_count': c['target_count'], 'benchmark_candidate_ids': [],
                'evidence_candidate_ids': [], 'gaps': ['No reviewed findings.'], 'rationale': 'Synthetic fixture.'}
                for c in payload['criteria']], 'next_searches': []}
        else:
            raise AssertionError(title)
        return self.cli.response(text=json.dumps(answer))

    def run_case(self, *flags, study=True, search=False, plan_only=False, include_urls=True):
        """Invoke the public terminal entry point with optional preliminary study controls.

        Args:
            self: Case with isolated source and provider fixtures.
            *flags: Extra terminal flags for budgets, extraction or fallback policy.
            study: Whether to opt into the new graph node.
            search: Whether to grant search permission independently.
            plan_only: Whether to stop immediately after the original planner.
            include_urls: False for a document-only input without the harness URL seed.
        Returns:
            Exit code, stdout, stderr, run directory and persisted session dictionary.
        """
        options = ['--max-requests', '25']
        if study:
            options.append('--coverage-study')
        if search:
            options.append('--search')
        result = self.cli.run_cli(self.provider, *options, *flags, plan_only=plan_only,
            source_dns=public_dns, details=False, include_urls=include_urls)
        directory, saved = self.cli.saved_session()
        return (*result, directory, saved)

    def test_bounded_study_precedes_loop_and_reuses_pages(self):
        """Real graph ordering and acquisition receipts establish the pilot's production path.

        Args:
            self: Case returning ten leads across two study queries.
        Returns:
            None. Assert four balanced pilot pages, shared counters, normal initial
            searches afterward and no duplicate source downloads or accepted claims.
        """
        code, out, err, directory, saved = self.run_case(search=True)
        self.assertEqual(code, 0, err)
        visits = saved['visited_nodes']
        self.assertLess(visits.index('review_plan'), visits.index('study_coverage'))
        self.assertLess(visits.index('study_coverage'), visits.index('schedule_work'))
        study = saved['coverage_study']
        self.assertEqual(study['status'], 'assessed')
        self.assertEqual(study['model_requests'], 3)
        self.assertEqual(len(study['source_ids']), 4)
        self.assertEqual(len(study['query_ids']), 2)
        requested = [r[1] for r in self.http.requests]
        for path in ('/probe-0-0', '/probe-1-0', '/probe-0-1', '/probe-1-1'):
            self.assertEqual(requested.count(path), 1)
        self.assertFalse(any('/probe-' in p and p.endswith(('-2', '-3', '-4')) for p in requested))
        self.assertEqual(self.searches[:2], [q['query'] for q in self.plan_queries])
        expected = [q for step in self.cli.plan['strategy'] for q in step['proposed_searches']]
        self.assertTrue(all(q in self.searches[2:] for q in expected))
        self.assertEqual(saved['usage']['requests_attempted'], len(self.cli.requests))
        self.assertEqual(saved['retrieval_usage']['http_requests'], len(self.http.requests))
        self.assertIsNone(saved['extraction'])
        self.assertFalse(saved['request']['stop_when_satisfied'])
        self.assertNotEqual(saved['workflow']['stop_reason'], 'criteria_satisfied')
        self.assertIn('Early coverage study: assessed', out)
        self.assertEqual(json.loads((directory / 'coverage_study.json').read_text()), study)
        graph = json.loads((directory / 'workflow_graph.json').read_text())['definition']
        edges = {(e['source'], e['target']) for e in graph['edges']}
        self.assertIn(('review_plan', 'study_coverage'), edges)
        self.assertIn(('study_coverage', 'schedule_work'), edges)

