    def test_four_supplied_pages_do_not_crowd_out_coverage_results(self):
        """A combined pool lets coverage results outrank a full four-page seed proposal.

        Args:
            self: Case supplying four profiles and selecting lower-ranked search rosters.
        Returns:
            None. Assert actual assessment pages follow the selected IDs, all candidates
            were exposed, and unchosen leads remain pending for ordinary research.
        """
        from projectclarity.research_schemas import ResearchSession
        from projectclarity.nodes.web_search.node import pending_search_results
        urls = ['https://example.org/research']
        for number in range(2, 5):
            path = f'/profile-{number}'
            urls.append('https://example.org' + path)
            self.routes[('example.org', path)] = (200, {'Content-Type': 'text/plain'}, b'Individual profile.')
        self.cli.urls.write_text('\n'.join(urls))
        self.seed_ids = ['S1', 'S2', 'S3', 'S4']
        self.selection_ids = ['R5', 'R9']
        _, _, _, directory, saved = self.run_case(search=True)
        pool = next(p for t, p in self.payloads if t == 'CoverageStudySelection')
        self.assertEqual({c['candidate_id'] for c in pool['candidates']},
            set(self.seed_ids + [f'R{i}' for i in range(1, 11)]))
        assessment = next(p for t, p in self.payloads if t == 'CoverageStudyAssessment')
        self.assertEqual({p['url_or_path'] for p in assessment['pages']},
            {'https://example.org/probe-0-4', 'https://example.org/probe-1-3'})
        self.assertEqual(saved['coverage_study']['source_ids'], ['S5', 'S6'])
        # Main selection may decline these later; inspect its input-time study checkpoint.
        main_call = next(json.loads(f.read_text()) for f in (directory / 'llm_calls').glob('search_select_*.json'))
        main_payload = json.loads(main_call['messages'][1]['content'])
        self.assertIn('R1', {r['result_id'] for r in main_payload['results']})
        snapshot = ResearchSession.model_validate(saved)
        snapshot.search['selections'] = [snapshot.search['selections'][0]]
        self.assertIn('R1', pending_search_results(snapshot))

