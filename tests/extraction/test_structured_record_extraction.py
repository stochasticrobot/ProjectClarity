"""Check preservation of HTML table/card records and repair of local extraction IDs.

The real parser subprocess handles constructed tables and frozen benchmark pages,
including shared cells, malformed spans and inherited headings. Separate controlled
reply tests exercise consistent replacement of invalid local IDs without changing
claims or quotations. No model replies are generated by a live service.
"""
import json
from pathlib import Path
import unittest

from projectclarity.extraction.local_identifier_recovery import recover_local_identifiers
from projectclarity.extraction.saved_source_passages import iter_passages, RECORD_START
from projectclarity.retrieval.document_text_extractor import parse_document
from projectclarity.retrieval.retrieval_limits import RetrievalError, RetrievalLimits


class StructuredRecordTests(unittest.TestCase):
    """Exercise the actual bounded parser and passage splitter on unseen table shapes."""

    def parse(self, html):
        """Run the production parser subprocess, not a test-only HTML formatter.

        Args:
            self: Test instance.
            html: Synthetic HTML string containing records to preserve.

        Returns:
            Normalized source text; parser failures propagate to unittest.
        """
        return parse_document(html.encode(), 'text/html', RetrievalLimits())[0]

    def test_shared_cells_headers_and_row_headers(self):
        """Keep a shared region attached to both holders and mixed TH/TD rows as data.

        Args:
            self: Test instance supplying assertions.

        Returns:
            None; fails if table structure produces a wrong or missing association.
        """
        text = self.parse('<main><table><tr><th>Name</th><th>Region</th><th>Period</th></tr>'
            '<tr><th scope="row">Aster</th><td rowspan="2">North</td><td>until 2020</td></tr>'
            '<tr><th scope="row">Birch</th><td>since 2020</td></tr></table></main>')
        self.assertIn('Name: Aster | Region: North | Period: until 2020', text)
        self.assertIn('Name: Birch | Region: North | Period: since 2020', text)
        self.assertEqual(len(RECORD_START.findall(text)), 2)

    def test_colspan_and_empty_cells_do_not_shift_later_columns(self):
        """Preserve blank column positions and source colspan semantics.

        Args:
            self: Test instance supplying assertions.

        Returns:
            None; fails if an empty/spanning cell changes column attribution.
        """
        text = self.parse('<table><tr><th>A</th><th>B</th><th>C</th></tr>'
            '<tr><td></td><td>Bee</td><td>Sea</td></tr>'
            '<tr><td colspan="2">Shared</td><td>Last</td></tr></table>')
        self.assertIn('B: Bee | C: Sea', text)
        self.assertIn('A: Shared | B: Shared | C: Last', text)

    def test_records_survive_bounded_passages_without_dropping_prose(self):
        """Partition complete tables/cards while covering all text exactly once.

        Args:
            self: Test instance supplying assertions.

        Returns:
            None; fails on split small records, oversized groups or omitted text.
        """
        cards = ''.join(f'<div class="item"><b>Person {i}</b><span>Place {i}</span></div>' for i in range(27))
        text = self.parse('<main><p>Before.</p><div>' + cards + '</div><p>After.</p></main>')
        self.assertEqual(len(RECORD_START.findall(text)), 27)
        passages = [text[start:end] for _, start, end in iter_passages(text)]
        self.assertEqual(''.join(passages), text)
        self.assertTrue(all(len(RECORD_START.findall(p)) <= 8 for p in passages))
        for i in range(27):
            self.assertEqual(sum(f'Person {i} | Place {i}\n' in p for p in passages), 1)
        self.assertIn('Before.', text)
        self.assertIn('After.', text)

    def test_malformed_colspan_keeps_party_and_candidate_columns_aligned(self):
        """Reproduce the saved Wikipedia attribute without importing a whole failed page.

        Args:
            self: Test instance supplying assertions.

        Returns:
            None; fails if recoverable header markup loses a row or shifts its fields.
        """
        text = self.parse('<main><p>Before table.</p><table>'
            '<tr><th bgcolor="" colspan="2 style=">Party</th><th>Candidate</th><th>Votes</th></tr>'
            '<tr><td></td><td>Maple</td><td>Aster</td><td>123</td></tr>'
            '<tr><td></td><td>Cedar</td><td>Birch</td><td>456</td></tr>'
            '</table><p>After table.</p></main>')
        self.assertIn('Party: Maple | Candidate: Aster | Votes: 123', text)
        self.assertIn('Party: Cedar | Candidate: Birch | Votes: 456', text)
        self.assertEqual(len(RECORD_START.findall(text)), 2)
        self.assertIn('Before table.', text)
        self.assertIn('After table.', text)

    def test_integer_prefix_recovery_keeps_shared_row_and_column_values(self):
        """Exercise recoverable span syntax on data cells as well as headers.

        Args:
            self: Test instance supplying assertions.

        Returns:
            None; fails if numeric-prefix parsing changes shared-field associations.
        """
        for span in ('2 style=', ' \t+02junk', '2.9', '2e3', '0' * 5000 + '2'):
            with self.subTest(span=span[:30]):
                text = self.parse('<table><tr><th>Name</th><th>Region</th><th>Period</th></tr>'
                    f'<tr><td>Aster</td><td rowspan="{span}">North</td><td>Earlier</td></tr>'
                    '<tr><td>Birch</td><td>Later</td></tr>'
                    f'<tr><td colspan="{span}">Shared</td><td>Final</td></tr></table>')
                self.assertIn('Name: Aster | Region: North | Period: Earlier', text)
                self.assertIn('Name: Birch | Region: North | Period: Later', text)
                self.assertIn('Name: Shared | Region: Shared | Period: Final', text)

    def test_invalid_attributes_default_to_one_without_shifting_columns(self):
        """Use HTML defaults for absent digits, negative values and non-ASCII numbers.

        Args:
            self: Test instance supplying assertions.

        Returns:
            None; fails on rejected readable tables or incorrect following-row positions.
        """
        for span in ('', 'style=2', '-2', '+ 2', '２', '\u00a02'):
            with self.subTest(span=span):
                text = self.parse('<table><tr><th>Name</th><th>Place</th></tr>'
                    f'<tr><td rowspan="{span}" colspan="{span}">Aster</td><td>North</td></tr>'
                    '<tr><td>Birch</td><td>South</td></tr></table>')
                self.assertIn('Name: Aster | Place: North', text)
                self.assertIn('Name: Birch | Place: South', text)

    def test_zero_colspan_defaults_to_one_and_rowspan_keeps_growing(self):
        """Keep the different zero meanings of colspan and rowspan in one row group.

        Args:
            self: Test instance supplying assertions.

        Returns:
            None; fails if zero spans drop a field or stop sharing before the last row.
        """
        for span in ('0', '-0', '+0junk'):
            with self.subTest(span=span):
                text = self.parse('<table><tr><th>Name</th><th>Place</th></tr>'
                    f'<tr><td colspan="{span}">Aster</td><td rowspan="{span}">North</td></tr>'
                    '<tr><td>Birch</td></tr><tr><td>Cedar</td></tr></table>')
                for name in ('Aster', 'Birch', 'Cedar'):
                    self.assertIn(f'Name: {name} | Place: North', text)

    def test_span_recovery_does_not_bypass_grid_or_output_limits(self):
        """Reject unsafe expansion and ambiguous overlaps instead of flattening them.

        Args:
            self: Test instance supplying assertions.

        Returns:
            None; fails if recovery silently accepts an oversized or conflicting grid.
        """
        for cells in ('<tr><td colspan="257 style=">Too wide</td></tr>',
                      '<tr><td colspan="256">Wide</td><td>Overflow</td></tr>',
                      '<tr><td colspan="' + '9' * 5000 + '">Huge</td></tr>',
                      '<tr><td rowspan="99999 style=">Too tall</td></tr>',
                      '<tr><td>First</td><td rowspan="2">Shared</td></tr>'
                      '<tr><td colspan="2 style=">Overlap</td></tr>'):
            with self.subTest(cells=cells[:90]):
                with self.assertRaises(RetrievalError) as caught:
                    self.parse('<table>' + cells + '</table>')
                self.assertEqual(caught.exception.code, 'parse_error')
        with self.assertRaises(RetrievalError) as caught:
            parse_document(('<table><tr><td colspan="100 style=">' + 'x' * 100 +
                '</td></tr></table>').encode(), 'text/html', RetrievalLimits(max_text_characters=500))
        self.assertEqual(caught.exception.code, 'text_size_limit')

    def test_frozen_pages_preserve_all_reference_pairs_in_single_records(self):
        """Check real dense input through production formatting, not model accuracy.

        Args:
            self: Test instance supplying assertions.

        Returns:
            None; fails if any source-local pair loses its shared record boundary.
        """
        root = Path(__file__).resolve().parents[2] / 'benchmarks/canadian_parliament'
        for stem in ('house_of_commons', 'wikipedia'):
            text, _ = parse_document((root / f'{stem}.html').read_bytes(), 'text/html', RetrievalLimits())
            blocks = text.split('\n\n')
            expected = json.loads((root / f'{stem}.expected.json').read_text())['expected_pairs']
            for row in expected:
                self.assertTrue(any(row['mp'] in block and row['riding'] in block for block in blocks), row)
            for match in RECORD_START.finditer(text):
                end = text.find('\n\n', match.end())
                end = len(text) if end < 0 else end
                if end - match.start() <= 12000:
                    self.assertTrue(any(a <= match.start() and b >= end for _, a, b in iter_passages(text)))


class LocalIdentifierRecoveryTests(unittest.TestCase):
    """Only formatting-local references can be repaired; assertions stay immutable."""

    def reply(self):
        """Create one independently authored claim with an overlong local label.

        Args:
            self: Test instance.

        Returns:
            JSON-compatible response dictionary without any benchmark answer data.
        """
        label = 'region_' + 'x' * 40
        return {'entities': [{'entity_id': 'person', 'name': 'Aster', 'entity_type': 'person'},
                             {'entity_id': label, 'name': 'North', 'entity_type': 'region'}],
                'claims': [{'claim_id': label, 'statement': 'Aster represents North.',
                    'goal_ids': ['G1'], 'entity_ids': ['person', label],
                    'relationship': {'subject_id': 'person', 'predicate': 'represents', 'object_id': label},
                    'qualifications': [], 'evidence': [{'passage_id': 'P1', 'quote': 'Aster represents North.'}]}]}

    def test_recovery_preserves_claims_quotes_and_separate_id_namespaces(self):
        """Alias entity/claim labels without collisions or semantic repairs.

        Args:
            self: Test instance supplying assertions.

        Returns:
            None; fails if any factual field or reference meaning changes.
        """
        payload = self.reply()
        parsed, aliases = recover_local_identifiers(json.dumps(payload))
        self.assertEqual(len(aliases), 2)
        self.assertNotEqual(parsed.claims[0].claim_id, parsed.entities[1].entity_id)
        self.assertEqual(parsed.claims[0].relationship.object_id, parsed.entities[1].entity_id)
        self.assertEqual(parsed.claims[0].statement, payload['claims'][0]['statement'])
        self.assertEqual(parsed.claims[0].evidence[0].quote, payload['claims'][0]['evidence'][0]['quote'])
        self.assertEqual(parsed.claims[0].goal_ids, ['G1'])

    def test_unknown_duplicate_and_unrelated_schema_errors_remain_failures(self):
        """Prevent local recovery from concealing identity ambiguity or broken evidence.

        Args:
            self: Test instance supplying assertions.

        Returns:
            None; fails if unsafe malformed replies are accepted.
        """
        payload = self.reply()
        payload['claims'][0]['relationship']['subject_id'] = 'invented'
        with self.assertRaises(ValueError):
            recover_local_identifiers(json.dumps(payload))
        payload = self.reply()
        payload['entities'].append(payload['entities'][1].copy())
        with self.assertRaises(ValueError):
            recover_local_identifiers(json.dumps(payload))
        payload = self.reply()
        payload['claims'][0]['evidence'][0]['quote'] = ''
        with self.assertRaises(ValueError):
            recover_local_identifiers(json.dumps(payload))


class RecordHeadingScopeTests(unittest.TestCase):
    """Keep real source headings with independent records, without inferring facts."""

    def test_heading_scope_survives_header_removal_and_late_passages(self):
        """Retain title and regional scope for every row after source passage splitting.

        Args:
            self: Assertion owner using unseen inventory tables and section headings.
        Returns:
            None; checks title retention, scope changes and exact normalized-text coverage.
        """
        rows = ''.join(f'<tr><td>Item{i}</td><td>Value{i}</td></tr>' for i in range(20))
        html = ('<main><header><h1>Active inventory</h1><span>Navigation furniture</span></header>'
            '<h2>North</h2><table><tr><th>Name</th><th>Value</th></tr>' + rows + '</table>'
            '<h2>South</h2><table><tr><th>Name</th><th>Value</th></tr><tr><td>Other</td><td>Last</td></tr></table></main>')
        text, parser = parse_document(html.encode(), 'text/html', RetrievalLimits())
        self.assertIn('records-v3', parser)
        self.assertNotIn('Navigation furniture', text)
        for index in range(20):
            self.assertIn(f'Source headings: Active inventory > North\nName: Item{index} | Value: Value{index}', text)
        self.assertIn('Source headings: Active inventory > South\nName: Other | Value: Last', text)
        passages = [text[start:end] for _, start, end in iter_passages(text)]
        self.assertEqual(''.join(passages), text)
        self.assertTrue(all('Source headings: Active inventory > North' in p for p in passages if 'Name: Item' in p))

    def test_card_headings_do_not_become_other_records_scope(self):
        """Do not carry a card's own name or embedded table heading into its siblings.

        Args:
            self: Assertion owner for repeated cards containing individual h3 titles.
        Returns:
            None; each card retains only its enclosing source heading as context.
        """
        cards = ''.join(f'<div class="item"><h3>Object{i}</h3><span>Detail{i}</span></div>' for i in range(3))
        html = '<main><h1>Catalogue</h1><h2>Current objects</h2><div>' + cards + '</div></main>'
        text, _ = parse_document(html.encode(), 'text/html', RetrievalLimits())
        for index in range(3):
            self.assertIn(f'Source headings: Catalogue > Current objects\nObject{index} | Detail{index}', text)
        self.assertNotIn('Current objects > Object', text)

    def test_both_saved_rosters_retain_real_heading_scope(self):
        """Check original HTML-derived context on both independent benchmark pages.

        Args:
            self: Assertion owner reading source HTML but no reference answer keys.
        Returns:
            None; confirms official membership scope and Wikipedia section geography
            remain visible inside records, without inventing an as-of publication date.
        """
        root = Path('benchmarks/canadian_parliament')
        official, _ = parse_document((root / 'house_of_commons.html').read_bytes(), 'text/html', RetrievalLimits())
        wiki, _ = parse_document((root / 'wikipedia.html').read_bytes(), 'text/html', RetrievalLimits())
        official_row = official.split('[Record C1]\n', 1)[1].split('\n\n', 1)[0]
        wiki_row = wiki.split('[Record T3R2]\n', 1)[1].split('\n\n', 1)[0]
        self.assertIn('Source headings: Current Members of Parliament', official_row)
        self.assertIn('House of Commons of Canada', official_row)
        self.assertIn('Source headings: List of House members of the 45th Parliament of Canada > Members > Alberta', wiki_row)
        self.assertIn('Document title:', wiki_row)
        self.assertNotIn('Source headings: 2026-10-26', official)
